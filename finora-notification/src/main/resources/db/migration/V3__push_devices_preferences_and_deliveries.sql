-- R7 (W3F): Expo Push. Thiết bị nhận push, tùy chọn theo nhóm thông báo và từng lần gửi push theo thiết bị.

-- Một dòng cho mỗi lần đăng ký token. Thu hồi (đăng xuất, Expo báo DeviceNotRegistered, chuyển sang tài khoản khác,
-- vượt giới hạn thiết bị) thì xóa token thô, chỉ giữ token_hash để đối chiếu: không giữ dữ liệu không còn dùng.
CREATE TABLE notification_push_devices (
    id UUID PRIMARY KEY,
    user_id VARCHAR(100) NOT NULL,
    token VARCHAR(255),
    token_hash VARCHAR(64) NOT NULL,
    platform VARCHAR(20) NOT NULL,
    app_version VARCHAR(40),
    status VARCHAR(20) NOT NULL,
    revoked_reason VARCHAR(40),
    last_registered_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_notification_push_devices_token UNIQUE (token),
    CONSTRAINT ck_notification_push_devices_platform CHECK (platform IN ('IOS', 'ANDROID', 'UNKNOWN')),
    CONSTRAINT ck_notification_push_devices_state CHECK (
        (status = 'ACTIVE' AND token IS NOT NULL AND revoked_at IS NULL AND revoked_reason IS NULL)
        OR (status = 'REVOKED' AND token IS NULL AND revoked_at IS NOT NULL AND revoked_reason IS NOT NULL))
);

-- Intake: WHERE user_id IN (...) AND status = 'ACTIVE'; giới hạn thiết bị: ORDER BY last_registered_at DESC.
CREATE INDEX idx_notification_push_devices_user_status
    ON notification_push_devices (user_id, status, last_registered_at);

-- Không có dòng nghĩa là bật push cho nhóm đó (mặc định sau khi người dùng cấp quyền hệ điều hành).
CREATE TABLE notification_preferences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(100) NOT NULL,
    category VARCHAR(30) NOT NULL,
    push_enabled BOOLEAN NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_notification_preferences_user_category UNIQUE (user_id, category)
);

-- Một thông báo trong app gửi push tới mỗi thiết bị đang hoạt động đúng một lần (unique notification + device).
-- title/body là bản đã che cho màn hình khóa: không số tiền, không tên, không mã khoản vay.
CREATE TABLE notification_push_deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id UUID NOT NULL,
    device_id UUID NOT NULL,
    recipient_id VARCHAR(100) NOT NULL,
    category VARCHAR(30) NOT NULL,
    title VARCHAR(100) NOT NULL,
    body VARCHAR(200) NOT NULL,
    provider VARCHAR(20),
    status VARCHAR(20) NOT NULL,
    attempt_count INTEGER NOT NULL,
    next_attempt_at TIMESTAMPTZ,
    ticket_id VARCHAR(100),
    receipt_check_after TIMESTAMPTZ,
    receipt_check_count INTEGER NOT NULL,
    last_error_code VARCHAR(60),
    sent_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_notification_push_deliveries_notification
        FOREIGN KEY (notification_id) REFERENCES in_app_notifications (id),
    CONSTRAINT fk_notification_push_deliveries_device
        FOREIGN KEY (device_id) REFERENCES notification_push_devices (id),
    CONSTRAINT uq_notification_push_deliveries_notification_device UNIQUE (notification_id, device_id),
    CONSTRAINT ck_notification_push_deliveries_status CHECK (
        status IN ('PENDING', 'SENDING', 'SENT', 'CONFIRMED', 'FAILED', 'DEAD', 'SKIPPED'))
);

-- Worker gửi: WHERE status IN ('PENDING','SENDING') AND next_attempt_at <= now ORDER BY next_attempt_at, id
-- FOR UPDATE SKIP LOCKED; SENDING quá hạn lease được nhận lại.
CREATE INDEX idx_notification_push_deliveries_dispatch
    ON notification_push_deliveries (status, next_attempt_at, id);

-- Worker đọc receipt của Expo: WHERE status = 'SENT' AND receipt_check_after <= now ORDER BY receipt_check_after, id.
CREATE INDEX idx_notification_push_deliveries_receipt
    ON notification_push_deliveries (status, receipt_check_after, id);

-- Màn vận hành: WHERE status = ? ORDER BY updated_at DESC, id DESC (DEAD/FAILED mới nhất trước), có phân trang.
CREATE INDEX idx_notification_push_deliveries_status_updated
    ON notification_push_deliveries (status, updated_at DESC, id DESC);
