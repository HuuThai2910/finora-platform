-- R7 (W3F): nhận event idempotent theo eventId, giữ event chưa biết người nhận và tra người nhận theo khoản vay.
-- Không có PII: chỉ ID logic (claim user_id), mã hồ sơ/hợp đồng/khoản vay và payload event đã không chứa PII theo contract.

-- 1) Hộp thư trong app: nhóm thông báo (để áp preference push) và phiên bản mẫu đã dùng khi render.
ALTER TABLE in_app_notifications
    ADD COLUMN category VARCHAR(30),
    ADD COLUMN template_version INTEGER NOT NULL DEFAULT 1,
    ADD COLUMN updated_at TIMESTAMPTZ;

-- Thông báo cũ chỉ đến từ InvestorNoteServicingChanged; loại lạ (nếu có) rơi về GENERAL.
UPDATE in_app_notifications
SET category = CASE type
        WHEN 'REPAYMENT_CREDITED' THEN 'REPAYMENT'
        WHEN 'EARLY_SETTLEMENT' THEN 'REPAYMENT'
        WHEN 'SETTLED' THEN 'REPAYMENT'
        WHEN 'RESCHEDULED' THEN 'RESTRUCTURING'
        WHEN 'DELINQUENCY_CURED' THEN 'DELINQUENCY'
        WHEN 'DELINQUENCY_CHANGED' THEN 'DELINQUENCY'
        WHEN 'BAD_DEBT_MILESTONE' THEN 'DELINQUENCY'
        ELSE 'GENERAL'
    END,
    updated_at = COALESCE(read_at, created_at);

ALTER TABLE in_app_notifications
    ALTER COLUMN category SET NOT NULL,
    ALTER COLUMN updated_at SET NOT NULL;

-- 2) Dấu đã xử lý của consumer, ghi cùng transaction với thông báo: Kafka giao lại cùng eventId thì bỏ qua.
CREATE TABLE notification_processed_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id UUID NOT NULL,
    event_type VARCHAR(100) NOT NULL,
    event_version INTEGER NOT NULL,
    source_topic VARCHAR(200) NOT NULL,
    outcome VARCHAR(30) NOT NULL,
    notification_count INTEGER NOT NULL,
    processed_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_notification_processed_events_event_id UNIQUE (event_id),
    CONSTRAINT ck_notification_processed_events_outcome
        CHECK (outcome IN ('DELIVERED', 'NO_RECIPIENT', 'FILTERED', 'EXPIRED_PARTIAL'))
);

-- 3) Event hợp lệ nhưng chưa biết người nhận (event khác topic chưa tới): giữ lại, worker thử lại có hạn.
CREATE TABLE notification_deferred_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id UUID NOT NULL,
    event_type VARCHAR(100) NOT NULL,
    event_version INTEGER NOT NULL,
    source_topic VARCHAR(200) NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL,
    payload_json JSONB NOT NULL,
    status VARCHAR(20) NOT NULL,
    wait_reason VARCHAR(100) NOT NULL,
    attempt_count INTEGER NOT NULL,
    next_attempt_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_notification_deferred_events_event_id UNIQUE (event_id),
    CONSTRAINT ck_notification_deferred_events_status CHECK (status IN ('WAITING', 'EXPIRED'))
);

-- Worker: WHERE status = 'WAITING' AND next_attempt_at <= now ORDER BY next_attempt_at, id LIMIT n.
CREATE INDEX idx_notification_deferred_events_status_next_attempt
    ON notification_deferred_events (status, next_attempt_at, id);

-- 4) Bảng tra người nhận theo khoản vay: event của Loan/Payment thiếu borrowerId/investorId (B64).
CREATE TABLE notification_loan_references (
    loan_application_id BIGINT PRIMARY KEY,
    borrower_id VARCHAR(100),
    application_number VARCHAR(64),
    contract_number VARCHAR(64),
    loan_number VARCHAR(64),
    lender_allocation_version BIGINT,
    last_source_event_id UUID NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

-- Nhà đầu tư theo allocation đã khóa (LoanFullyFunded.v2); chỉ dùng cho các bước trước khi Note đổi chủ.
CREATE TABLE notification_loan_lenders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_application_id BIGINT NOT NULL,
    investor_id VARCHAR(100) NOT NULL,
    allocation_version BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_notification_loan_lenders_loan
        FOREIGN KEY (loan_application_id) REFERENCES notification_loan_references (loan_application_id),
    CONSTRAINT uq_notification_loan_lenders_loan_investor UNIQUE (loan_application_id, investor_id)
);
