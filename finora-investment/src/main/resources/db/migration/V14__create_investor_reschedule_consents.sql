CREATE TABLE investment_reschedule_consents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id UUID NOT NULL,
    loan_application_id BIGINT NOT NULL,
    loan_number VARCHAR(50) NOT NULL,
    request_type VARCHAR(40) NOT NULL,
    reschedule_from_date DATE NOT NULL,
    adjusted_due_date DATE,
    extra_terms INTEGER,
    original_maturity_date DATE,
    investor_id VARCHAR(100) NOT NULL,
    outstanding_principal NUMERIC(18,2) NOT NULL,
    status VARCHAR(20) NOT NULL,
    decision_comment VARCHAR(500),
    decision_idempotency_key VARCHAR(150),
    decided_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_investment_reschedule_consent UNIQUE (request_id, investor_id),
    CONSTRAINT ck_investment_reschedule_consent_type CHECK (
        request_type IN ('INSTALLMENT_ADJUSTMENT', 'TERM_EXTENSION')
    ),
    CONSTRAINT ck_investment_reschedule_consent_status CHECK (
        status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED')
    ),
    CONSTRAINT ck_investment_reschedule_consent_principal CHECK (outstanding_principal > 0),
    CONSTRAINT ck_investment_reschedule_consent_shape CHECK (
        (request_type = 'INSTALLMENT_ADJUSTMENT' AND adjusted_due_date IS NOT NULL AND extra_terms IS NULL)
        OR (request_type = 'TERM_EXTENSION' AND adjusted_due_date IS NULL AND extra_terms > 0)
    )
);

CREATE INDEX idx_investment_reschedule_consent_investor
    ON investment_reschedule_consents (investor_id, status, created_at DESC);

CREATE INDEX idx_investment_reschedule_consent_request
    ON investment_reschedule_consents (request_id, status);
