-- 1. Chặn người vay tự góp vốn khoản của mình. ID logic người vay đến từ LoanFundingRequested v1
--    (trường bổ sung); listing tạo trước đó để null và không bị kiểm.
ALTER TABLE market_listings ADD COLUMN borrower_id VARCHAR(100);

-- 2. Worker nhả khoản giữ của lệnh đặt vốn đã kết thúc (huỷ do hết hạn gọi vốn, bị từ chối sau khi
--    đã giữ tiền, lần nhả trước lỗi mạng). Bảng chỉ có vài dòng thoả điều kiện tại một thời điểm.
CREATE INDEX ix_order_release_pending
    ON investment_orders (id)
    WHERE status IN ('CANCELLED', 'REJECTED')
      AND payment_hold_reference IS NOT NULL AND payment_released_at IS NULL;

-- 3. Lệnh mua trên sổ bị từ chối khi kẹt chờ giữ tiền cũng cần nhả khoản giữ đối soát.
DROP INDEX idx_order_book_orders_release_pending;
CREATE INDEX idx_order_book_orders_release_pending
    ON order_book_orders (id)
    WHERE side = 'BID' AND status IN ('FILLED', 'CANCELLED', 'REJECTED')
      AND hold_reference IS NOT NULL AND hold_released_at IS NULL;

-- 4. Khoản trả nợ Payment đã chia cho chủ cũ của Note (Payment chưa nhận NoteOwnershipChanged),
--    cần chuyển lại cho chủ hiện tại. Mỗi (repayment, Note) tối đa một khoản.
CREATE TABLE note_repayment_redirects (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    redirect_reference  VARCHAR(100)  NOT NULL,
    repayment_id        UUID          NOT NULL,
    note_id             BIGINT        NOT NULL,
    from_investor_id    VARCHAR(100)  NOT NULL,
    to_investor_id      VARCHAR(100)  NOT NULL,
    amount              NUMERIC(18,2) NOT NULL,
    status              VARCHAR(20)   NOT NULL,
    attempts            INT           NOT NULL DEFAULT 0,
    next_attempt_at     TIMESTAMPTZ   NOT NULL,
    last_error_code     VARCHAR(50),
    payment_reference   VARCHAR(100),
    completed_at        TIMESTAMPTZ,
    version             BIGINT        NOT NULL DEFAULT 0,
    created_at          TIMESTAMPTZ   NOT NULL,
    updated_at          TIMESTAMPTZ   NOT NULL,

    CONSTRAINT fk_note_repayment_redirects_note FOREIGN KEY (note_id) REFERENCES investment_notes (id),
    CONSTRAINT ck_note_repayment_redirects_amount CHECK (amount > 0),
    CONSTRAINT ck_note_repayment_redirects_parties CHECK (from_investor_id <> to_investor_id),
    CONSTRAINT ck_note_repayment_redirects_status CHECK (status IN ('PENDING', 'COMPLETED', 'FAILED')),
    CONSTRAINT ck_note_repayment_redirects_completed CHECK (
        (status = 'COMPLETED') = (completed_at IS NOT NULL AND payment_reference IS NOT NULL))
);

CREATE UNIQUE INDEX uq_note_repayment_redirects_reference ON note_repayment_redirects (redirect_reference);
CREATE UNIQUE INDEX uq_note_repayment_redirects_repayment_note ON note_repayment_redirects (repayment_id, note_id);
CREATE INDEX idx_note_repayment_redirects_due
    ON note_repayment_redirects (next_attempt_at, id)
    WHERE status = 'PENDING';
