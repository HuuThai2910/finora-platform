-- Giấy xác nhận chuyển nhượng Note: mỗi lần khớp đã thanh toán xong có đúng một văn bản PDF do FINORA phát hành và đóng
-- dấu số PAdES. Worker lập văn bản sau khi khớp, không nằm trong transaction khớp lệnh: lỗi gọi User, dựng PDF hay ký
-- chỉ làm văn bản chậm lại, không ảnh hưởng quyền sở hữu Note. PDF lưu ở đây; Blockchain chỉ nhận SHA-256 qua outbox.
CREATE TABLE note_transfer_documents (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trade_id              BIGINT        NOT NULL,
    trade_reference       VARCHAR(50)   NOT NULL,
    document_number       VARCHAR(60)   NOT NULL,
    loan_id               BIGINT        NOT NULL,
    listing_id            BIGINT        NOT NULL,

    status                VARCHAR(20)   NOT NULL,
    attempts              INT           NOT NULL DEFAULT 0,
    next_attempt_at       TIMESTAMPTZ,
    last_error            VARCHAR(200),

    -- Chỉ có khi ISSUED: PDF đã ký, SHA-256 của chính bytes đó và object data của event NoteTransferDocumentIssued
    -- (artifact để người kiểm toán tính lại hash đã neo trên ledger).
    content               BYTEA,
    content_hash          VARCHAR(64),
    proof_payload         TEXT,
    seal_subject          VARCHAR(200),
    issued_at             TIMESTAMPTZ,

    created_at            TIMESTAMPTZ   NOT NULL,
    updated_at            TIMESTAMPTZ   NOT NULL,

    CONSTRAINT fk_note_transfer_documents_trade FOREIGN KEY (trade_id) REFERENCES order_book_trades (id),
    CONSTRAINT ck_note_transfer_documents_status CHECK (status IN ('PENDING', 'ISSUED', 'FAILED')),
    CONSTRAINT ck_note_transfer_documents_attempts CHECK (attempts >= 0),
    CONSTRAINT ck_note_transfer_documents_issued CHECK (
        (status = 'ISSUED') = (content IS NOT NULL AND content_hash IS NOT NULL
            AND proof_payload IS NOT NULL AND issued_at IS NOT NULL))
);

CREATE UNIQUE INDEX uq_note_transfer_documents_trade ON note_transfer_documents (trade_id);
CREATE UNIQUE INDEX uq_note_transfer_documents_trade_reference ON note_transfer_documents (trade_reference);
CREATE UNIQUE INDEX uq_note_transfer_documents_number ON note_transfer_documents (document_number);

-- Hàng đợi lập văn bản theo lượt thử kế tiếp.
CREATE INDEX ix_note_transfer_documents_due
    ON note_transfer_documents (next_attempt_at, id)
    WHERE status = 'PENDING';

-- Trang quản trị: mới nhất trước, lọc theo trạng thái.
CREATE INDEX ix_note_transfer_documents_status_created
    ON note_transfer_documents (status, created_at DESC, id DESC);
