-- Liên kết tài khoản ngân hàng nhận tiền rút (BL-001). Mỗi người dùng có 0..N tài khoản đã liên kết; mỗi lần liên kết
-- đi qua đúng một yêu cầu xác thực OTP. Rút tiền tham chiếu tài khoản đã liên kết thay vì nhận số tài khoản gõ tay.

-- Yêu cầu liên kết đang chờ OTP: ngân hàng đã xác nhận chủ tài khoản, chờ người dùng nhập mã ngân hàng gửi.
CREATE TABLE payment_bank_link_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    link_request_id UUID NOT NULL,
    owner_id VARCHAR(100) NOT NULL,
    bank_code VARCHAR(20) NOT NULL,
    -- AES-256-GCM "v1:<base64(iv|ciphertext|tag)>" như số tài khoản của lệnh rút (D44).
    account_number_encrypted VARCHAR(512) NOT NULL,
    -- HMAC-SHA256 hex của số tài khoản: so trùng mà không giải mã.
    account_fingerprint VARCHAR(64) NOT NULL,
    account_number_masked VARCHAR(32) NOT NULL,
    account_holder_name VARCHAR(100) NOT NULL,
    -- HMAC-SHA256 hex của mã OTP gắn với link_request_id; không lưu mã OTP gốc.
    otp_hash VARCHAR(64) NOT NULL,
    otp_expires_at TIMESTAMPTZ NOT NULL,
    otp_sent_at TIMESTAMPTZ NOT NULL,
    failed_attempts INT NOT NULL DEFAULT 0,
    resend_count INT NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL,
    idempotency_key VARCHAR(150) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_payment_bank_link_requests_id UNIQUE (link_request_id),
    -- Gửi lại cùng Idempotency-Key (cùng token PIN) trả đúng yêu cầu cũ, không gửi thêm OTP.
    CONSTRAINT uq_payment_bank_link_requests_owner_key UNIQUE (owner_id, idempotency_key),
    CONSTRAINT ck_payment_bank_link_requests_status CHECK (status IN ('PENDING', 'CONFIRMED', 'LOCKED', 'EXPIRED')),
    CONSTRAINT ck_payment_bank_link_requests_fingerprint CHECK (account_fingerprint ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_payment_bank_link_requests_otp_hash CHECK (otp_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_payment_bank_link_requests_counts CHECK (failed_attempts >= 0 AND resend_count >= 0)
);

CREATE TABLE payment_bank_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bank_account_id UUID NOT NULL,
    owner_id VARCHAR(100) NOT NULL,
    bank_code VARCHAR(20) NOT NULL,
    account_number_encrypted VARCHAR(512) NOT NULL,
    account_fingerprint VARCHAR(64) NOT NULL,
    account_number_masked VARCHAR(32) NOT NULL,
    account_holder_name VARCHAR(100) NOT NULL,
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(20) NOT NULL,
    link_request_id UUID NOT NULL REFERENCES payment_bank_link_requests (link_request_id),
    linked_at TIMESTAMPTZ NOT NULL,
    removed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_payment_bank_accounts_id UNIQUE (bank_account_id),
    CONSTRAINT uq_payment_bank_accounts_link_request UNIQUE (link_request_id),
    CONSTRAINT ck_payment_bank_accounts_status CHECK (status IN ('ACTIVE', 'REMOVED')),
    CONSTRAINT ck_payment_bank_accounts_removed CHECK ((status = 'REMOVED') = (removed_at IS NOT NULL)),
    CONSTRAINT ck_payment_bank_accounts_default CHECK (NOT is_default OR status = 'ACTIVE'),
    CONSTRAINT ck_payment_bank_accounts_fingerprint CHECK (account_fingerprint ~ '^[0-9a-f]{64}$')
);

-- Một tài khoản (ngân hàng + số) chỉ liên kết một lần với một người dùng; huỷ liên kết rồi liên kết lại được.
CREATE UNIQUE INDEX uq_payment_bank_accounts_active_account
    ON payment_bank_accounts (owner_id, bank_code, account_fingerprint) WHERE status = 'ACTIVE';

-- Tối đa một tài khoản mặc định cho mỗi người dùng.
CREATE UNIQUE INDEX uq_payment_bank_accounts_default ON payment_bank_accounts (owner_id) WHERE is_default;

-- Danh sách tài khoản của người dùng: WHERE owner_id = ? AND status = 'ACTIVE'.
CREATE INDEX ix_payment_bank_accounts_owner ON payment_bank_accounts (owner_id, linked_at DESC) WHERE status = 'ACTIVE';
