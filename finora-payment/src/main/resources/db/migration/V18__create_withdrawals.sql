-- R4 (W3B): rút tiền từ ví về tài khoản ngân hàng qua provider payout.
-- Tiền rời ví ngay lúc nhận lệnh (bút toán WITHDRAWAL vào clearing PAYOUT_PROVIDER_CLEARING, D41); thất bại thì hoàn bằng
-- bút toán ngược. Một ví có 0..N lệnh rút; mỗi lệnh thuộc đúng một ví.
CREATE TABLE payment_withdrawals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    withdrawal_id UUID NOT NULL,
    wallet_id UUID NOT NULL REFERENCES payment_wallets (wallet_id),
    owner_type VARCHAR(20) NOT NULL,
    owner_id VARCHAR(100) NOT NULL,
    amount NUMERIC(19, 2) NOT NULL,
    fee_amount NUMERIC(19, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    -- Ngày nghiệp vụ Asia/Ho_Chi_Minh lúc nhận lệnh: hạn mức rút trong ngày cộng theo cột này, không theo ngày UTC.
    business_date DATE NOT NULL,
    status VARCHAR(30) NOT NULL,
    bank_code VARCHAR(20) NOT NULL,
    -- AES-256-GCM "v1:<base64(iv|ciphertext|tag)>" (D44); API chỉ trả bản che.
    account_number_encrypted VARCHAR(512) NOT NULL,
    account_number_masked VARCHAR(32) NOT NULL,
    account_holder_name VARCHAR(100) NOT NULL,
    idempotency_key VARCHAR(150) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    provider VARCHAR(30) NOT NULL,
    provider_reference VARCHAR(100),
    reserve_ledger_transaction_id UUID NOT NULL,
    refund_ledger_transaction_id UUID,
    attempt_count INT NOT NULL DEFAULT 0,
    reconciliation_attempt_count INT NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ,
    error_code VARCHAR(80),
    error_detail VARCHAR(500),
    manual_recheck_count INT NOT NULL DEFAULT 0,
    last_manual_recheck_by VARCHAR(100),
    last_manual_recheck_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_payment_withdrawals_withdrawal_id UNIQUE (withdrawal_id),
    -- Gửi lại cùng Idempotency-Key của cùng chủ ví trả lệnh cũ, không tạo lệnh rút thứ hai.
    CONSTRAINT uq_payment_withdrawals_owner_key UNIQUE (owner_id, idempotency_key),
    CONSTRAINT ck_payment_withdrawals_owner_type CHECK (owner_type IN ('BORROWER', 'INVESTOR')),
    CONSTRAINT ck_payment_withdrawals_amount CHECK (amount > 0),
    CONSTRAINT ck_payment_withdrawals_fee CHECK (fee_amount >= 0),
    CONSTRAINT ck_payment_withdrawals_currency CHECK (currency ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_payment_withdrawals_request_hash CHECK (request_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_payment_withdrawals_status CHECK (status IN (
        'REQUESTED', 'PROCESSING', 'PROVIDER_PENDING', 'RECONCILIATION_REQUIRED', 'COMPLETED', 'FAILED')),
    CONSTRAINT ck_payment_withdrawals_completed CHECK ((status = 'COMPLETED') = (completed_at IS NOT NULL)),
    -- Lệnh thất bại luôn đã hoàn tiền trong cùng transaction.
    CONSTRAINT ck_payment_withdrawals_refund CHECK ((status = 'FAILED') = (refund_ledger_transaction_id IS NOT NULL)),
    CONSTRAINT ck_payment_withdrawals_counts CHECK (
        attempt_count >= 0 AND reconciliation_attempt_count >= 0 AND manual_recheck_count >= 0)
);

-- Lịch sử rút của người dùng: WHERE owner_id = ? ORDER BY created_at DESC.
CREATE INDEX ix_payment_withdrawals_owner_created ON payment_withdrawals (owner_id, created_at DESC, id DESC);

-- Hạn mức ngày: SUM(amount) WHERE wallet_id = ? AND business_date = ? AND status <> 'FAILED' (đọc khi đã khóa dòng ví).
CREATE INDEX ix_payment_withdrawals_daily ON payment_withdrawals (wallet_id, business_date) WHERE status <> 'FAILED';

-- Hàng đợi worker: lệnh chưa kết thúc tới lượt xử lý/tra cứu theo next_attempt_at; NULL là chờ vận hành.
CREATE INDEX ix_payment_withdrawals_due ON payment_withdrawals (next_attempt_at, id)
    WHERE status IN ('REQUESTED', 'PROCESSING', 'PROVIDER_PENDING', 'RECONCILIATION_REQUIRED')
      AND next_attempt_at IS NOT NULL;

-- Callback của provider tìm lệnh theo provider_reference.
CREATE UNIQUE INDEX uq_payment_withdrawals_provider_reference ON payment_withdrawals (provider_reference)
    WHERE provider_reference IS NOT NULL;
