-- R5 (D13, Q9, W3C): hợp đồng nhiều bên mới được ký PAdES-B-B nhúng thẳng vào PDF, mỗi chữ ký là một bản cập nhật
-- gia tăng (incremental update) nối tiếp bản trước. Hợp đồng tạo trước V32 giữ luồng bằng chứng tách rời
-- (DETACHED_EVIDENCE): không đổi bytes, hash, trạng thái hay cách ký của chúng.
ALTER TABLE loan_contracts
    ADD COLUMN signature_profile VARCHAR(30) NOT NULL DEFAULT 'DETACHED_EVIDENCE';

-- PAdES chỉ áp dụng cho hợp đồng nhiều bên (lập sau LoanFullyFunded); hợp đồng một bên kiểu LN-008 là dữ liệu cũ.
ALTER TABLE loan_contracts
    ADD CONSTRAINT ck_loan_contract_signature_profile CHECK (
        signature_profile IN ('DETACHED_EVIDENCE', 'PADES_B_B')
        AND (signature_profile = 'DETACHED_EVIDENCE' OR multi_party)
    );

-- SIGNED_PDF là bản PAdES cuối (đủ chữ ký) công bố cho các bên. Vẫn giữ ràng buộc một bản mỗi loại trên một Contract;
-- các bản trung gian của chuỗi chữ ký nằm ở loan_contract_signatures, không nới UNIQUE(contract_id, artifact_type).
ALTER TABLE loan_contract_documents DROP CONSTRAINT ck_loan_contract_document_type;
ALTER TABLE loan_contract_documents ADD CONSTRAINT ck_loan_contract_document_type CHECK (
    artifact_type IN ('SIGNABLE', 'SIGNED_PDF', 'SIGNED_RECEIPT')
);

-- Mỗi dòng là một lần ký của một bên: PREPARED giữ bytes có chỗ trống chữ ký và signed attributes đã gửi provider;
-- SIGNED giữ đúng bytes sau khi nhúng CMS; ABANDONED là lần ký bị từ chối/hết phiên, không thuộc chuỗi chữ ký.
CREATE TABLE loan_contract_signatures (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id BIGINT NOT NULL,
    signer_type VARCHAR(20) NOT NULL,
    signer_id VARCHAR(100) NOT NULL,
    sequence_number SMALLINT NOT NULL,
    attempt_number SMALLINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    signature_format VARCHAR(30) NOT NULL,
    signature_provider VARCHAR(30) NOT NULL,
    signature_method VARCHAR(30) NOT NULL,
    provider_transaction_id VARCHAR(150) NOT NULL,
    provider_document_id VARCHAR(100) NOT NULL,
    idempotency_key VARCHAR(150) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    base_content_hash VARCHAR(64) NOT NULL,
    content BYTEA NOT NULL,
    content_hash VARCHAR(64) NOT NULL,
    content_length INTEGER NOT NULL,
    signature_contents_offset INTEGER NOT NULL,
    signature_contents_length INTEGER NOT NULL,
    document_digest VARCHAR(64) NOT NULL,
    signed_attributes BYTEA NOT NULL,
    signed_attributes_digest VARCHAR(64) NOT NULL,
    signing_time TIMESTAMPTZ NOT NULL,
    certificate BYTEA NOT NULL,
    certificate_chain BYTEA,
    certificate_serial VARCHAR(80) NOT NULL,
    certificate_sha256 VARCHAR(64) NOT NULL,
    cms_hash VARCHAR(64),
    evidence_hash VARCHAR(64),
    abandon_reason VARCHAR(50),
    prepared_at TIMESTAMPTZ NOT NULL,
    signed_at TIMESTAMPTZ,
    abandoned_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_loan_contract_signature_contract FOREIGN KEY (contract_id) REFERENCES loan_contracts (id),
    CONSTRAINT uq_loan_contract_signatures_attempt UNIQUE (contract_id, signer_type, signer_id, attempt_number),
    CONSTRAINT uq_loan_contract_signatures_provider_tx UNIQUE (signature_provider, provider_transaction_id),
    CONSTRAINT ck_loan_contract_signature_signer CHECK (signer_type IN ('LENDER', 'BORROWER')),
    CONSTRAINT ck_loan_contract_signature_status CHECK (status IN ('PREPARED', 'SIGNED', 'ABANDONED')),
    CONSTRAINT ck_loan_contract_signature_format CHECK (signature_format = 'PADES_B_B'),
    CONSTRAINT ck_loan_contract_signature_provider CHECK (
        (signature_provider = 'MOCK' AND signature_method = 'CLICK_WRAP_MVP')
        OR (signature_provider = 'VNPT_SMART_CA' AND signature_method = 'VNPT_SMART_CA')
    ),
    CONSTRAINT ck_loan_contract_signature_numbers CHECK (sequence_number > 0 AND attempt_number > 0),
    CONSTRAINT ck_loan_contract_signature_hashes CHECK (
        length(request_hash) = 64 AND length(base_content_hash) = 64 AND length(content_hash) = 64
        AND length(document_digest) = 64 AND length(signed_attributes_digest) = 64
        AND length(certificate_sha256) = 64
    ),
    CONSTRAINT ck_loan_contract_signature_content CHECK (
        content_length > 0 AND octet_length(content) = content_length
        AND signature_contents_offset > 0 AND signature_contents_length > 2
        AND signature_contents_offset + signature_contents_length < content_length
    ),
    CONSTRAINT ck_loan_contract_signature_lifecycle CHECK (
        (status = 'PREPARED' AND signed_at IS NULL AND abandoned_at IS NULL AND abandon_reason IS NULL
            AND cms_hash IS NULL AND evidence_hash IS NULL)
        OR
        (status = 'SIGNED' AND signed_at IS NOT NULL AND abandoned_at IS NULL AND abandon_reason IS NULL
            AND length(cms_hash) = 64 AND length(evidence_hash) = 64)
        OR
        (status = 'ABANDONED' AND signed_at IS NULL AND abandoned_at IS NOT NULL
            AND abandon_reason IN (
                'PROVIDER_REJECTED', 'PROVIDER_SIGNATURE_INVALID', 'SIGNING_SESSION_EXPIRED', 'CONTRACT_CLOSED'
            )
            AND cms_hash IS NULL AND evidence_hash IS NULL)
    )
);

-- Một Contract chỉ có một phiên ký đang chờ: chữ ký PAdES phải nối tiếp nhau trên cùng một chuỗi bytes,
-- hai bên cùng chuẩn bị trên một bản gốc sẽ tạo hai nhánh mà chỉ một nhánh được nhúng.
CREATE UNIQUE INDEX uq_loan_contract_signatures_in_flight
    ON loan_contract_signatures (contract_id) WHERE status = 'PREPARED';
-- Mỗi vị trí trong chuỗi chỉ có một bản đã ký; cũng là index đọc bản mới nhất và danh sách cho trang biên nhận.
CREATE UNIQUE INDEX uq_loan_contract_signatures_sequence
    ON loan_contract_signatures (contract_id, sequence_number) WHERE status = 'SIGNED';
-- Một bên ký (nhà đầu tư hoặc người vay) có đúng một chữ ký trên hợp đồng dù sở hữu nhiều phần vốn.
CREATE UNIQUE INDEX uq_loan_contract_signatures_signer
    ON loan_contract_signatures (contract_id, signer_type, signer_id) WHERE status = 'SIGNED';
-- Worker đối soát phiên SmartCA chỉ quét các phiên đang chờ, cũ trước.
CREATE INDEX idx_loan_contract_signatures_in_flight_due
    ON loan_contract_signatures (prepared_at, id) WHERE status = 'PREPARED';
