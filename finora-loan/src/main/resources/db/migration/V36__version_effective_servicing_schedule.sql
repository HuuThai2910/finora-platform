CREATE TABLE loan_servicing_schedule_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    finora_loan_id BIGINT NOT NULL,
    reschedule_request_id UUID NOT NULL,
    schedule_version INTEGER NOT NULL,
    periods_snapshot_json JSONB NOT NULL,
    data_as_of TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_servicing_schedule_version_loan FOREIGN KEY (finora_loan_id) REFERENCES finora_loans (id),
    CONSTRAINT uq_servicing_schedule_version_request UNIQUE (reschedule_request_id),
    CONSTRAINT uq_servicing_schedule_version_number UNIQUE (finora_loan_id, schedule_version),
    CONSTRAINT ck_servicing_schedule_version_positive CHECK (schedule_version > 0)
);

CREATE INDEX idx_servicing_schedule_version_latest
    ON loan_servicing_schedule_versions (finora_loan_id, schedule_version DESC);
